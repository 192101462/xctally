# One-time migration: turn <repo>\apps\android into the real Android Studio project,
# so that "Update Project" (Ctrl+T) + Run is the whole workflow.
#
# Run this ONCE on the build machine, then open <repo>\apps\android in Android Studio
# instead of the old separate project folder.
#
#   tools\adopt-studio-project.cmd -Project "D:\AndroidStudioProjects\xctally" -Repo "D:\xcnote"
#
# Why this removes the sync step:
#   The web app is not copied into the module any more. app/build.gradle.kts gets an
#   extra asset source dir pointing at ../../prototype (inside the same repo), so the
#   APK is built straight from the repo files. Pull -> Run. Nothing to sync.
#
# ASCII-only, no BOM (see copy-into-android-project.ps1).

param(
    [Parameter(Mandatory = $true)][string]$Project,
    [Parameter(Mandatory = $true)][string]$Repo
)

$ErrorActionPreference = 'Stop'

if (-not (Test-Path $Project)) { throw "Studio project not found: $Project" }
if (-not (Test-Path $Repo)) { throw "Repo clone not found: $Repo" }

$src = (Resolve-Path $Project).Path
$repo = (Resolve-Path $Repo).Path
$target = Join-Path $repo 'apps\android'
$webDir = Join-Path $repo 'prototype'

if (-not (Test-Path (Join-Path $src 'app\build.gradle.kts'))) {
    throw "That does not look like the Studio project (no app\build.gradle.kts): $src"
}
if (-not (Test-Path (Join-Path $webDir 'index.html'))) {
    throw "Repo does not look right (no prototype\index.html): $repo"
}
if (-not (Test-Path (Join-Path $target 'app\src\main\AndroidManifest.xml'))) {
    throw "Repo does not look right (no apps\android\app\src\main\AndroidManifest.xml): $repo"
}

Write-Host "Adopting Studio scaffolding into the repo" -ForegroundColor Cyan
Write-Host "  from: $src"
Write-Host "  into: $target"
Write-Host ""

function Copy-Into([string]$rel) {
    $from = Join-Path $src $rel
    if (-not (Test-Path $from)) {
        Write-Host ("  [skip]  " + $rel + "  (not in the Studio project)") -ForegroundColor DarkGray
        return
    }
    $to = Join-Path $target $rel
    $dir = Split-Path -Parent $to
    if (-not (Test-Path $dir)) { New-Item -ItemType Directory -Force -Path $dir | Out-Null }
    if ((Get-Item $from).PSIsContainer) {
        if (Test-Path $to) { Remove-Item $to -Recurse -Force }
        Copy-Item $from $to -Recurse -Force
    } else {
        Copy-Item $from $to -Force
    }
    Write-Host ("  [copy]  " + $rel) -ForegroundColor Green
}

# ---------------------------------------------------------------- build scaffolding
# gradle wrapper, root build files, module build file: all generated by Android Studio,
# all version-correct for this machine, so take them as they are.
Copy-Into 'gradlew'
Copy-Into 'gradlew.bat'
Copy-Into 'gradle'
Copy-Into 'build.gradle.kts'
Copy-Into 'settings.gradle.kts'
Copy-Into 'gradle.properties'
Copy-Into 'app\build.gradle.kts'
Copy-Into 'app\proguard-rules.pro'

# launcher icons and any other generated resources (keep our own values/ and xml/)
foreach ($d in @('app\src\main\res\mipmap-mdpi', 'app\src\main\res\mipmap-hdpi',
                 'app\src\main\res\mipmap-xhdpi', 'app\src\main\res\mipmap-xxhdpi',
                 'app\src\main\res\mipmap-xxxhdpi', 'app\src\main\res\mipmap-anydpi-v26',
                 'app\src\main\res\drawable', 'app\src\main\res\drawable-v24')) {
    Copy-Into $d
}

# ---------------------------------------------------------------- asset source dir
# Point the module's assets at prototype/ inside the same repo, and drop the old copy.
$gradlePath = Join-Path $target 'app\build.gradle.kts'
$gx = [System.IO.File]::ReadAllText($gradlePath, [System.Text.Encoding]::UTF8)

if ($gx -notmatch 'assets\.srcDirs') {
    $anchor = 'android {'
    $idx = $gx.IndexOf($anchor)
    if ($idx -lt 0) { throw "Could not find 'android {' in $gradlePath" }

    $header = @'
// The web app in the repo IS this module's asset dir - no copy, so "Update Project"
// (Ctrl+T) plus Run is the whole workflow.
// srcDirs resolves relative paths against the MODULE dir (apps/android/app), and a
// wrong path fails silently (empty assets -> white screen in the app), so anchor it
// on rootProject and fail the build loudly if it is missing.
val webAssetsDir = rootProject.projectDir.resolve("../../prototype")
require(webAssetsDir.isDirectory) {
    "Web assets not found: $webAssetsDir (expected <repo>/prototype)"
}

'@
    $inner = @'
    sourceSets {
        getByName("main") {
            assets.srcDirs(webAssetsDir)
        }
    }

'@
    # single deterministic splice: header before "android {", sourceSets just inside it
    $gx = $gx.Substring(0, $idx) + $header + $anchor + "`r`n" + $inner +
          $gx.Substring($idx + $anchor.Length)
    $utf8NoBom = New-Object System.Text.UTF8Encoding($false)
    [System.IO.File]::WriteAllText($gradlePath, $gx, $utf8NoBom)
    Write-Host "  [edit]  app\build.gradle.kts: assets.srcDirs -> <repo>\prototype" -ForegroundColor Green
} else {
    Write-Host "  [ok]    app\build.gradle.kts already has assets.srcDirs" -ForegroundColor DarkGray
}

# remove the old copied assets so Gradle cannot merge stale files
$oldAssets = Join-Path $target 'app\src\main\assets'
if (Test-Path $oldAssets) {
    Remove-Item $oldAssets -Recurse -Force
    Write-Host "  [del]   app\src\main\assets  (no longer needed)" -ForegroundColor Yellow
}

Write-Host ""
Write-Host "Done. Next steps:" -ForegroundColor Cyan
Write-Host ""
Write-Host "1) commit what we just adopted, so every machine gets it:"
Write-Host "     cd /d $repo"
Write-Host "     git add -A"
Write-Host "     git commit -m ""android: adopt the Studio project into the repo"""
Write-Host "     git push"
Write-Host ""
Write-Host "2) in Android Studio: File - Open...  ->  $target"
Write-Host "   (let it sync once; the old project folder can be deleted afterwards)"
Write-Host ""
Write-Host "3) from now on the whole workflow is:"
Write-Host "     Ctrl+T  (Update Project)   ->   Run"
Write-Host "   No sync script, no cmd file."
